/* 由 data.js 生成配套的《明朝卫所与海防大事表》Markdown（与图同源，避免抄录误差） */
const fs = require('fs');
const path = require('path');
const { loadContext } = require('./load');

const ctx = loadContext();
const D = ctx.FB_DATA;

const evs = D.events.slice().sort((a, b) => a.y - b.y);
const segCount = 2;
const per = Math.ceil(evs.length / segCount);

const CN = ['一', '二', '三', '四'];
const rows = evs.map((e, i) => {
  const seg = Math.floor(i / per);
  return {
    seg: '卷' + CN[seg],
    y: e.y,
    era: e.era,
    tag: e.tag,
    title: e.title,
    points: (e.points || []).join('；'),
    src: e.src,
  };
});

const head = `| 卷 | 公元 | 纪年 | 类别 | 大事 | 要点 | 出处 |
|:--:|:--:|:--|:--:|:--|:--|:--|`;
const body = rows
  .map((r) => `| ${r.seg} | ${r.y} | ${r.era} | ${r.tag} | **${r.title}** | ${r.points} | ${r.src} |`)
  .join('\n');

const eraRows = D.eras
  .map((er) => {
    const mine = evs.filter((e) => e.y >= er.from && e.y <= er.to);
    const tags = {};
    mine.forEach((e) => (tags[e.tag] = (tags[e.tag] || 0) + 1));
    const ts = Object.keys(tags).map((k) => `${k}${tags[k]}`).join('·');
    return `| ${er.full} | ${er.span} | ${mine.length} | ${ts} |`;
  })
  .join('\n');

const doc = `# 明朝卫所与海防大事表（1368—1644）

> 与《明朝卫所与海防鱼骨纪事表》同源配套。全表 ${evs.length} 条，按时间先后排列；
> 每条均可回溯至《明史》志书与列传、《明太祖实录》、《东西洋考》等原始文献。
> 排版代码见 \`index.html\` 与 \`src/\`，图与表由同一份数据生成。

## 一、分期与条目分布

| 分期 | 年代 | 条数 | 类别构成 |
|:--|:--|:--:|:--|
${eraRows}

## 二、大事表

${head}
${body}

## 三、卫所制度要点（制度线）

1. **编制**：五千六百人为卫，千一百二十人为千户所，百十有二人为百户所；所下五十人为总旗、十人为小旗。卫设指挥使，所设千户、百户。
2. **统属**：外统于都司（行都司、留守司），内统于五军都督府；兵部掌调兵之令，五府掌统兵之权，兵籍在府、军令在部，互相牵制。
3. **军户**：军皆世籍，世代承役，一户军、一户贴；逃亡、故绝则清军勾补，故"尺籍久虚"而"行伍衰耗"。
4. **屯田**：军屯自给，边地三分守城七分屯种（一说二八），腹里二分守城八分屯种；屯田败坏即卫所败坏。
5. **班军**：卫所军轮番赴京操练、赴边戍守，"疲于番上"，京师之旅"困于占役"。
6. **衰变**：正统土木之变后京军尽没，于谦改团营，卫所军主力地位渐为募兵、家丁取代；至明末卫所惟存虚籍。

## 四、海防体系要点（海防线）

1. **沿海卫所**：自辽东、山东、直隶、浙江、福建、广东，卫所棋布；洪武间汤和筑山东、浙东西沿海五十九城，周德兴筑福建沿海十六城。
2. **水军与战船**：洪武三年置水军二十四卫，每卫船五十艘；沿海设水寨、巡海备倭，春汛、秋汛出洋会哨。
3. **海禁与海防一体**：禁濒海民私通海外，徙海岛居民，坚壁清野；海防遂成"岸防"，与"片板不许下海"互为表里。
4. **外向期**：永乐至宣德，郑和七下西洋，海疆由守转出，"以海制海"；停罢之后复归岸守。
5. **倭患与重构**：嘉靖二年宁波争贡、二十六年朱纨整饬、三十年代倭乱大炽；戚继光练义乌兵、创鸳鸯阵，俞大猷、胡宗宪水陆并进，至嘉靖四十三年东南平定。海防实已由卫所转为募兵＋水寨＋将兵。
6. **开海与崩解**：隆庆开海（月港）以商制寇；万历援朝露梁海战为明代远海最后一胜；荷兰东来据澎湖、台湾，天启崇祯间海防重心北移渤海，终随国亡而瓦解。

## 五、阅读与使用

- 鱼骨图的横轴为**编年纪脊**，骨刺按时间先后自脊线斜出（默认倾角 75°，水平位移 = 离轴高度 ÷ tan75°）；
- 由于每条骨刺要铺开标题、两条要点与图片位，刻度间距按内容**弹性展开**（间距供阅读，标注的纪年为真实纪年，先后次序严格递增）；
- 骨刺上下交替分列脊线两侧，长卷可分"卷"，以免单幅过长；
- 点击任一条骨刺，可查看史料补充说明、上传配图、修改图中文字；改动仅存本机浏览器。

## 六、主要参考

- 《明史》卷八九—九一《兵志》、卷八一《食货志五》、卷一二六《汤和传》、卷一三〇《周德兴传》、卷一五五《刘荣传》、卷二〇五《朱纨传》《张经传》《胡宗宪传》、卷二一二《戚继光传》、卷二四七《邓子龙传》、卷三〇四《郑和传》、卷三二〇《朝鲜传》、卷三二五《和兰传》、卷三二七《鞑靼传》等。
- 《明太祖实录》《明太宗实录》。
- 张燮《东西洋考》卷七《饷税考》；江日昇《台湾外记》。
- 版式思路参考：天宁《利用 svg 结合 html 实现时间轴上下斜着展示子节点的鱼骨图》，博客园，2023。
`;

fs.writeFileSync(path.join(__dirname, '..', '明朝卫所与海防大事表.md'), doc, 'utf8');
console.log('✓ 明朝卫所与海防大事表.md  ' + (doc.length / 1024).toFixed(1) + ' KB / ' + evs.length + ' 条');